// Builds the Jawa Tengah place data for the city picker (P3) from cahyadsn/wilayah
// (MIT; codes per Kepmendagri No 300.2.2-2138 Tahun 2025). Run: node scripts/region-data.mjs
//
// Writes src/lib/region/:
//   jateng.ts          kota/kabupaten and their kecamatan
//   jateng-villages.ts desa/kelurahan per kota/kabupaten (loaded when searching)
//   jateng-shapes.ts   simplified outlines (loaded only for "Use my location")
// The source's MIT licence is kept next to them in LICENSE-wilayah.txt.

import { writeFileSync } from "node:fs";

const PROVINCE = "33";
const BASE = "https://raw.githubusercontent.com/cahyadsn/wilayah/master/db";
const OUT = new URL("../src/lib/region/", import.meta.url);

const [levels12, all] = await Promise.all(
  ["wilayah_level_1_2.sql", "wilayah.sql"].map(async (f) => {
    const res = await fetch(`${BASE}/${f}`);
    if (!res.ok) throw new Error(`${f}: ${res.status}`);
    return res.text();
  }),
);

// ('33.73','Kota Salatiga','Salatiga', -7.33, 110.50, …, '[[lat,lng],…]', 1);
const regencies = [];
for (const m of levels12.matchAll(/\('(33\.\d\d)','([^']+)','[^']*',[^']*'(\[[^']*\])'/g)) {
  const [, code, name, shape] = m;
  regencies.push({
    id: code.replace(".", ""),
    // "Kabupaten Boyolali" → "Kab. Boyolali", the short form used on screen.
    name: name.replace(/^Kabupaten /, "Kab. "),
    rings: rings(JSON.parse(shape)),
  });
}
if (regencies.length !== 35) throw new Error(`expected 35 kota/kabupaten, got ${regencies.length}`);

const districts = new Map(regencies.map((r) => [r.id, []]));
const villages = new Map(regencies.map((r) => [r.id, []]));
for (const m of all.matchAll(/\('(33)\.(\d\d)\.(\d\d)(?:\.(\d{4}))?','([^']+)'\)/g)) {
  const [, , kab, , village, name] = m;
  const id = `${PROVINCE}${kab}`;
  if (!districts.has(id)) continue;
  // Village codes: 1xxx kelurahan, 2xxx desa.
  if (village) villages.get(id).push(`${village[0] === "1" ? "k" : "d"}${clean(name)}`);
  else districts.get(id).push(clean(name));
}
const districtCount = [...districts.values()].reduce((n, d) => n + d.length, 0);
if (districtCount < 570) throw new Error(`expected ~576 kecamatan, got ${districtCount}`);

const header = `// Generated by scripts/region-data.mjs from cahyadsn/wilayah (MIT),
// codes per Kepmendagri No 300.2.2-2138 Tahun 2025. Don't edit by hand.
`;

writeFileSync(
  new URL("jateng.ts", OUT),
  `${header}
/** [BPS code, name] */
export const REGENCIES: [string, string][] = ${JSON.stringify(regencies.map((r) => [r.id, r.name]))};

/** Kecamatan per kota/kabupaten, "|"-separated. */
export const DISTRICTS: Record<string, string> = ${JSON.stringify(Object.fromEntries([...districts].map(([id, d]) => [id, d.join("|")])), null, 0)};
`,
);

writeFileSync(
  new URL("jateng-villages.ts", OUT),
  `${header}
/** Desa ("d") and kelurahan ("k") per kota/kabupaten, "|"-separated, each prefixed with its kind. */
export const VILLAGES: Record<string, string> = ${JSON.stringify(Object.fromEntries([...villages].map(([id, v]) => [id, v.join("|")])))};
`,
);

writeFileSync(
  new URL("jateng-shapes.ts", OUT),
  `${header}
/** Simplified outlines (~300 m), [lat, lng] rings per kota/kabupaten. Never stored or sent anywhere. */
export const SHAPES: Record<string, [number, number][][]> = ${JSON.stringify(Object.fromEntries(regencies.map((r) => [r.id, r.rings])))};
`,
);

console.log(`${regencies.length} kota/kabupaten, ${districtCount} kecamatan, ${[...villages.values()].reduce((n, v) => n + v.length, 0)} desa/kelurahan`);

// ── helpers ──────────────────────────────────────────────────────────────

function round(n, places) {
  const f = 10 ** places;
  return Math.round(n * f) / f;
}

function clean(name) {
  return name.replace(/\s+/g, " ").trim();
}

/** One ring or several (islands), simplified and rounded. */
function rings(shape) {
  // Shapes nest at different depths (polygon, multipolygon); a ring is an array of [lat, lng].
  const list = [];
  // Some source shapes are malformed (Kota Semarang mixes a ring and loose points
  // in one array), so runs of points anywhere count as a ring.
  const isPoint = (n) => Array.isArray(n) && typeof n[0] === "number";
  const collect = (node) => {
    let run = [];
    for (const child of node) {
      if (isPoint(child)) run.push(child);
      else if (Array.isArray(child)) {
        if (run.length) list.push(run);
        run = [];
        collect(child);
      }
    }
    if (run.length) list.push(run);
  };
  collect(shape);
  return list
    .map((ring) => simplify(ring, 0.003).map(([lat, lng]) => [round(lat, 4), round(lng, 4)]))
    .filter((ring) => ring.length >= 4);
}

/** Douglas–Peucker on lat/lng degrees. */
function simplify(points, tolerance) {
  if (points.length < 3) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let max = 0;
    let index = -1;
    for (let i = a + 1; i < b; i++) {
      const d = distanceToSegment(points[i], points[a], points[b]);
      if (d > max) {
        max = d;
        index = i;
      }
    }
    if (max > tolerance) {
      keep[index] = 1;
      stack.push([a, index], [index, b]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

function distanceToSegment([y, x], [y1, x1], [y2, x2]) {
  const dx = x2 - x1;
  const dy = y2 - y1;
  const len = dx * dx + dy * dy;
  const t = len ? Math.max(0, Math.min(1, ((x - x1) * dx + (y - y1) * dy) / len)) : 0;
  return Math.hypot(x - (x1 + t * dx), y - (y1 + t * dy));
}
