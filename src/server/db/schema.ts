import { bigint, boolean, date, index, integer, jsonb, pgSequence, pgTable, primaryKey, text, timestamp, bigserial } from "drizzle-orm/pg-core";

// Server-side storage (step 7). The phone stays the source of truth; the
// server keeps a copy per account so plans follow the user across devices.

/** Every write gets the next value, so a device can pull "everything since version N". */
export const syncVersion = pgSequence("sync_version");

/**
 * One row per synced local record: settings, weeks, slots, list items and the
 * user's own/edited dishes. `data` is the device's record as-is; `deleted`
 * carries removals. Last write wins by the device's `updated_at`.
 */
export const syncRows = pgTable(
  "sync_rows",
  {
    userId: text("user_id").notNull(),
    entity: text("entity").notNull(),
    key: text("key").notNull(),
    data: jsonb("data"),
    deleted: boolean("deleted").notNull().default(false),
    updatedAt: bigint("updated_at", { mode: "number" }).notNull(),
    version: bigint("version", { mode: "number" }).notNull(),
  },
  (t) => [primaryKey({ columns: [t.userId, t.entity, t.key] }), index("sync_rows_user_version").on(t.userId, t.version)],
);

/** Shared dish library: each unknown dish is generated by AI once, then reused by everyone. */
export const dishLibrary = pgTable("dish_library", {
  nameKey: text("name_key").primaryKey(),
  dish: jsonb("dish").notNull(),
  recognized: boolean("recognized").notNull(),
  model: text("model").notNull(),
  hits: integer("hits").notNull().default(0),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

/** "Report a wrong ingredient", sent from devices with sync. */
export const ingredientReports = pgTable("ingredient_reports", {
  id: bigserial("id", { mode: "number" }).primaryKey(),
  userId: text("user_id"),
  report: jsonb("report").notNull(),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

/** Daily AI generation counts, to cap spend (per account, per anonymous guest, and overall). */
export const aiUsage = pgTable(
  "ai_usage",
  {
    bucket: text("bucket").notNull(),
    day: date("day", { mode: "string" }).notNull(),
    count: integer("count").notNull().default(0),
  },
  (t) => [primaryKey({ columns: [t.bucket, t.day] })],
);
